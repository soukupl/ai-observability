import { createHash, randomBytes } from 'node:crypto';

/** Crockford base32, as used by ULID. */
const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
const TIME_LEN = 10;
const RANDOM_LEN = 16;
const MAX_TIME = 2 ** 48 - 1;

function encodeTime(ms: number): string {
  if (!Number.isFinite(ms) || ms < 0 || ms > MAX_TIME) throw new RangeError(`ulid: invalid time ${ms}`);
  let t = Math.floor(ms);
  let out = '';
  for (let i = 0; i < TIME_LEN; i++) {
    out = ALPHABET[t % 32] + out;
    t = Math.floor(t / 32);
  }
  return out;
}

/** 80 bits → 16 base32 digits (as an array of digit values 0..31). */
function bytesToDigits(bytes: Uint8Array): number[] {
  let bits = 0n;
  for (let i = 0; i < 10; i++) bits = (bits << 8n) | BigInt(bytes[i] ?? 0);
  const digits: number[] = new Array(RANDOM_LEN);
  for (let i = RANDOM_LEN - 1; i >= 0; i--) {
    digits[i] = Number(bits & 31n);
    bits >>= 5n;
  }
  return digits;
}

const digitsToString = (d: number[]) => d.map((v) => ALPHABET[v]).join('');

let lastTime = -1;
let lastRandom: number[] = [];

/**
 * Monotonic ULID: lexicographically sortable by time; within the same millisecond the random part is
 * incremented, so IDs generated by one process are strictly increasing.
 */
export function ulid(now: number = Date.now()): string {
  if (now <= lastTime && lastRandom.length) {
    const next = [...lastRandom];
    let i = RANDOM_LEN - 1;
    while (i >= 0 && next[i] === 31) next[i--] = 0;
    if (i < 0) throw new Error('ulid: random part overflow within one millisecond');
    next[i] = (next[i] ?? 0) + 1;
    lastRandom = next;
    return encodeTime(lastTime) + digitsToString(next);
  }
  lastTime = now;
  lastRandom = bytesToDigits(randomBytes(10));
  return encodeTime(now) + digitsToString(lastRandom);
}

/**
 * Deterministic ULID from a seed: same seed + time → same ID. Used for event IDs so that re-processing
 * a transcript after a crash produces the same `event_id`s, which the server de-duplicates (ADR-0011).
 */
export function ulidFrom(seed: string, timeMs: number): string {
  const hash = createHash('sha256').update(seed).digest();
  return encodeTime(Math.min(Math.max(0, timeMs), MAX_TIME)) + digitsToString(bytesToDigits(hash));
}

/** Milliseconds encoded in a ULID's time part. */
export function decodeTime(id: string): number {
  let t = 0;
  for (const ch of id.slice(0, TIME_LEN).toUpperCase()) {
    const v = ALPHABET.indexOf(ch);
    if (v < 0) throw new Error(`ulid: invalid character "${ch}"`);
    t = t * 32 + v;
  }
  return t;
}

export const ULID_RE = /^[0-9A-HJKMNP-TV-Z]{26}$/;
